def dump_tz_context(tz_context: Optional[Dict[str, Any]] = None) -> Any:
    """
    Преобразует входной контекст ТЗ в JSON-строку для prompt.

    Args:
        tz_context: полученный из ТЗ в формате словаря
    Returns:
        ТЗ в формате JSON
    Применяется в функции ainvoke_llm
    """
    # Если контекст ТЗ уже передан из backend — сериализуем его напрямую

    try:
        return json.dumps(
            tz_context,
            ensure_ascii=False,   # Русский текст оставляем читаемым
            separators=(",", ":"), # Компактный JSON без лишних пробелов
        )
    except Exception as e:
        log.exception(f"Ошибка сериализации tz_context: {e}")
        return "{}"


def dump_tt_context(tt_context: Optional[Dict[str, Any]] = None) -> str:
    """Преобразует контекст ТТ в JSON-строку для prompt.

    Args:
        tt_context: найденные сущности и чанки ТТ для одного блока.
    Returns:
        str: компактный JSON с контекстом ТТ.
    Применяется в функции ainvoke_llm
    """

    try:
        return json.dumps(
            tt_context or {},
            ensure_ascii=False,
            separators=(",", ":"),
        )
    except Exception as err:
        log.exception(f"Ошибка сериализации tt_context: {err}")
        return "{}"

def dump_doc_context(
    doc_context: Optional[Dict[str, Any]] = None,
) -> str:
    """Преобразует общий контекст документа в компактный JSON.

    Args:
        doc_context: общая информация о проверяемом документе.

    Returns:
        str: компактный JSON для передачи в LLM prompt.

    Применяется:
        В run_format_check(), run_tz_check(), run_tt_check().
    """

    try:
        return json.dumps(
            doc_context or {},
            ensure_ascii=False,  # Сохраняем русский текст читаемым.
            separators=(",", ":"),  # Удаляем лишние пробелы для уменьшения prompt.
        )
    except Exception as err:
        log.exception(
            f"Ошибка сериализации doc_context: {err}"
        )  # Ошибка общего контекста не должна останавливать анализ.

        return "{}"


