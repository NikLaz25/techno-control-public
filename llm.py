def _block_to_dict(block: Any) -> Dict[str, Any]:
    """
    Приводит block к dict независимо от того:
    - это dict (как приходит "чистым JSON")
    - это Pydantic-модель (как сейчас: backend.app.schemas.WordBlock)
    Args:
        block - список блоков
    Returns:
        dict - словарь с входящими блоками
    Применяется в функции run_llm_check
    """  # Комментарий: единая нормализация входа

    if isinstance(block, dict):  # Если это уже словарь — ничего не делаем
        return block  # Возвращаем как есть

    # Pydantic v2: model_dump()  # Комментарий: основной путь для pydantic>=2
    if hasattr(block, "model_dump") and callable(getattr(block, "model_dump")):
        return block.model_dump()  # Превращаем модель в dict

    # Pydantic v1: dict()  # Комментарий: запасной путь для pydantic<2
    if hasattr(block, "dict") and callable(getattr(block, "dict")):
        return block.dict()  # Превращаем модель в dict

    # Последний fallback: пробуем взять __dict__ (не идеально, но лучше чем падение)  # Комментарий: крайний случай
    if hasattr(block, "__dict__"):
        return dict(block.__dict__)  # Преобразуем атрибуты объекта в dict

    return {}  # Если вообще не получилось — возвращаем пустой словарь

MAX_BLOCK_CHARS_FOR_LLM = 2200 # Назначение: Не отправлять в LLM слишком длинные блоки целиком.

def trim_block_for_llm(text: str) -> str:
    """
    Обрезает текст блока до допустимого размера для передачи в LLM.

    Назначение:
    - ограничивает длину входного текста, чтобы не превышать лимиты модели;
    - предотвращает ошибки structured output (переполнение токенов);
    - обеспечивает стабильную работу LLM при обработке длинных документов.

    Args:
        text: исходный текст блока документа

    Returns:
        str: текст, ограниченный по длине для безопасной передачи в LLM
    Применяется в функции run_llm_check
    """
    src = str(text or "")
    if len(src) <= MAX_BLOCK_CHARS_FOR_LLM:
        return src

    # Обрезаем аккуратно для MVP.
    return src[:MAX_BLOCK_CHARS_FOR_LLM]

# ============================================================================
# Назначение: Нормализует текст для сравнения LLM-координат с исходным block_text.
# ============================================================================
def normalize_for_offset_check(value: str) -> str:
    '''
    Нормализует текст для проверки координат ошибки.
    Args:
        value: исходный текст для нормализации.
    Returns:
        str: нормализованный текст для проверки offset-координат.
    Применяется в функции validate_llm_offsets
    '''
    return (
        str(value or "")
        .replace("\u0005", "")
        .replace("\u00ad", "")
        .replace("\xa0", " ")
        .replace("\r\n", "\n")
        .replace("\r", "\n")
    )

# ============================================================================
# Назначение: Проверяет, что start/end действительно указывают на text_err.
# ============================================================================
def validate_llm_offsets(block_text: str, start: int, end: int, text_err: str) -> bool:
    '''
    Проверяет корректность координат ошибки, возвращённых LLM.

    Назначение:
        Убедиться, что координаты start/end действительно указывают
        на тот же фрагмент текста, который LLM указала в text_err.

    Зачем нужно:
        Word Add-in использует start/end для точной привязки замечания
        к диапазону текста. Если координаты неверные, frontend может
        подсветить не тот фрагмент или не сможет создать issue-якорь.

    Алгоритм:
        1. Нормализует текст блока документа.
        2. Нормализует текст ошибочного фрагмента.
        3. Проверяет типы и границы start/end.
        4. Вырезает из блока фрагмент по координатам.
        5. Сравнивает вырезанный фрагмент с text_err.

    Args:
        block_text: полный текст проверяемого блока документа.
        start: индекс первого символа ошибки, включительно.
        end: индекс конца ошибки, не включительно.
        text_err: ошибочный фрагмент текста, который вернула LLM.

    Returns:
        bool: True, если координаты корректны; False, если координаты
        невалидны или не совпадают с text_err.
    Применяется в функции run_llm_check
    '''
    src = normalize_for_offset_check(block_text)
    err = normalize_for_offset_check(text_err)

    if not isinstance(start, int) or not isinstance(end, int):
        return False

    if start < 0 or end < start or end > len(src):
        return False

    fragment = src[start:end]
    return fragment.strip() == err.strip()

def normalize_table_context(
    block_text: str,
    context: str,
    match: str,
    block_type: str,
) -> str:
    """
    Ограничивает контекст замечания одной ячейкой таблицы.

    Args:
        block_text: Исходный текст Word-блока.
        context: Контекст, возвращённый LLM.
        match: Ошибочный фрагмент, возвращённый LLM.
        block_type: Тип Word-блока.

    Returns:
        str: Контекст внутри одной ячейки либо пустую строку,
        если ошибочный фрагмент пересекает границы ячеек
        или отсутствует в исходных ячейках.

    Где применяется:
        app/llm_openai.py:
        run_tz_check(), run_tt_check().
    """

    # Приводим входные значения к строкам.
    safe_block_text = str(block_text or "")
    safe_context = str(context or "")
    safe_match = str(match or "")
    safe_block_type = str(block_type or "").strip().lower()

    # Обычные текстовые блоки не изменяем.
    if safe_block_type != "table":
        return safe_context

    # Запрещаем ошибочному фрагменту пересекать границы ячеек.
    if not safe_match or any(
        char in safe_match for char in ("\t", "\n", "\r")
    ):
        return ""

    # Делим исходную таблицу на ячейки.
    # Одиночные и двойные табуляции выступают разделителями.
    source_cells = [
        cell
        for cell in safe_block_text.split("\t")
        if cell
    ]

    # Проверяем, что ошибка находится хотя бы в одной исходной ячейке.
    matching_source_cells = [
        cell
        for cell in source_cells
        if safe_match in cell
    ]

    # Фрагмент не относится ни к одной отдельной ячейке.
    if not matching_source_cells:
        return ""

    # Если контекст уже принадлежит одной исходной ячейке,
    # сохраняем его без изменений.
    if (
        "\t" not in safe_context
        and "\n" not in safe_context
        and "\r" not in safe_context
        and safe_match in safe_context
        and any(
            safe_context in cell
            for cell in matching_source_cells
        )
    ):
        return safe_context

    # Делим полученный от LLM контекст по границам ячеек.
    context_cells = [
        cell.strip()
        for cell in safe_context.split("\t")
        if cell.strip()
    ]

    # Выбираем только фрагменты, которые содержат ошибку
    # и буквально присутствуют в исходной ячейке.
    matching_context_cells = [
        cell
        for cell in context_cells
        if safe_match in cell
        and any(
            cell in source_cell
            for source_cell in matching_source_cells
        )
        and "\n" not in cell
        and "\r" not in cell
    ]

    # Если подходящий контекст единственный, используем его.
    if len(matching_context_cells) == 1:
        return matching_context_cells[0]

    # При неоднозначности сохраняем только ошибочный фрагмент.
    # Его нахождение внутри исходной ячейки уже проверено.
    return safe_match


