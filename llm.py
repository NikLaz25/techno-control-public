# 9. ИТОГОВЫЕ ФУНКЦИИ В ДАННОМ МОДУЛЕ
async def run_format_check(
    block: Dict[str, Any],
) -> List[Dict[str, Any]]:
    """
    Проверяет один Word-блок только по Правилу 1.

    Args:
        block: Один блок документа Word

    Returns:
        List[Dict[str, Any]]: Список замечаний в общем backend-формате:

    Где применяется:
        - в отдельном pipeline проверки Rule 1;
        - может запускаться параллельно с run_tz_check() и run_tt_check();
        - результат затем передаётся в общий post_proc().

    """

    # Итоговый список замечаний по текущему Word-блоку.
    issues: List[Dict[str, Any]] = []

    # ------------------------------------------------------------------------
    # 1. Нормализация входного Word-блока
    # ------------------------------------------------------------------------

    # Защищаем функцию от None и других неожиданных значений.
    safe_block = block if isinstance(block, dict) else {}

    # Получаем ID блока.
    # blockId необходим frontend для поиска блокового Content Control.
    block_id = str(safe_block.get("id", "") or "").strip()

    # Получаем тип блока:
    # paragraph, heading, list или table.
    block_type = str(safe_block.get("type", "") or "").strip()

    # Получаем нужную полезную часть метаданных
    block_meta = (safe_block.get("meta", {}) or {})
    block_meta = str(block_meta.get('styles', {}) or {})

    # Получаем исходный текст блока без изменения символов.
    #
    # Важно: именно относительно этой строки LLM должен вычислить start/end.
    source_block_text = str(safe_block.get("text", "") or "")

    # Если ID блока отсутствует, замечания нельзя надёжно связать
    # с конкретным блоком Word.
    if not block_id:
        log.warning(
            "LLM run_format_check: проверка пропущена, "
            "потому что у блока отсутствует id"
        )
        return []

    # Пустой текст проверять не нужно.
    if not source_block_text.strip():
        log.debug(
            f"LLM run_format_check: пустой текст, "
            f"проверка пропущена block_id={block_id}"
        )
        return []

    log.debug(
        f"LLM run_format_check: start "
        f"block_id={block_id} "
        f"block_type={block_type} "
        f"text_len={len(source_block_text)}"
    )

    # ------------------------------------------------------------------------
    # 2. Подготовка текста для LLM
    # ------------------------------------------------------------------------

    # Ограничиваем слишком большой блок действующим helper-методом.
    # trim_block_for_llm() защищает LLM-вызов от чрезмерного объёма текста.
    # - уменьшает риск переполнения контекстного окна; ограничивает длительность и стоимость запроса.
    llm_block_text = trim_block_for_llm(source_block_text)

    # Фиксируем факт обрезки.
    # Если блок был обрезан, offsets LLM нельзя автоматически считать
    # координатами исходного полного блока.
    was_trimmed = len(llm_block_text) != len(source_block_text)

    # Дополнительная защита на случай, если trim_block_for_llm()
    # вернул пустую строку.
    if not llm_block_text.strip():
        log.warning(
            f"LLM run_format_check: после trim_block_for_llm текст пустой "
            f"block_id={block_id}"
        )
        return []

    # ------------------------------------------------------------------------
    # 3. Создание отдельной LLM-цепочки Rule 1
    # ------------------------------------------------------------------------
    # Собираем LangChain Runnable:
    _format_llm_chain = get_format_chain()

    # ------------------------------------------------------------------------
    # 4. Асинхронный вызов LLM
    # ------------------------------------------------------------------------

    try:
        # ainvoke() является асинхронным сетевым вызовом.
        # Во время ожидания ответа event loop может выполнять проверки
        # других блоков и обслуживать другие запросы.
        async with LLM_REQUEST_SEM:
            llm_result: LlmOutStructure = await _format_llm_chain.ainvoke(
                {
                    "document_block": llm_block_text,
                    "block_type": block_type,
                    "block_meta": block_meta,
                }
            )
    except Exception as err:
        # Ошибка проверки одного блока не должна останавливать
        # проверку всего документа.
        log.exception(
            f"LLM run_format_check: ошибка LLM-вызова "
            f"block_id={block_id}: {err}"
        )
        return []

    # Нормализуем список ответа.
    llm_errors = list(getattr(llm_result, "llm_out", []) or [])

    log.debug(
        f"LLM run_format_check: LLM завершил проверку "
        f"block_id={block_id} "
        f"raw_issues={len(llm_errors)}"
    )

    # ------------------------------------------------------------------------
    # 5. Преобразование ошибок LLM в backend issues
    # ------------------------------------------------------------------------
    for error_index, err in enumerate(llm_errors, start=1):
        # Rule 1 имеет право возвращать только format_err.
        #
        # Даже если модель нарушила prompt и вернула tz_err или tt_err,
        # такое замечание отбрасывается на backend.
        error_type = str(getattr(err, "type_err", "") or "").strip().lower()

        if error_type != "format_err":
            log.warning(
                f"LLM run_format_check: пропущен недопустимый type_err "
                f"block_id={block_id} "
                f"error_index={error_index} "
                f"type_err={error_type!r}"
            )
            continue

        # Получаем буквальный ошибочный фрагмент, который вернула модель.
        raw_match = str(getattr(err, "text_err", "") or "")

        # Получаем буквальный контекст ошибки.
        raw_context = str(getattr(err, "context_err", "") or "")

        # Получаем предлагаемое исправление.
        raw_correct = str(getattr(err, "correct_err", "") or "")

        # Получаем пояснение для панели.
        raw_message = str(getattr(err, "msg_err", "") or "").strip()

        # Получаем критичность, определённую моделью.
        critic_err = str(
            getattr(err, "critic_err", "") or ""
        ).strip().lower()

        # Без ошибочного фрагмента frontend не сможет найти место ошибки.
        if not raw_match:
            log.warning(
                f"LLM run_format_check: пропущено замечание без text_err "
                f"block_id={block_id} "
                f"error_index={error_index}"
            )
            continue

        # text_err обязан буквально присутствовать в тексте,
        # который был передан модели.
        #
        # Эта проверка блокирует галлюцинации, при которых модель
        # возвращает изменённый или придуманный фрагмент.
        if raw_match not in llm_block_text:
            log.warning(
                f"LLM run_format_check: text_err отсутствует в document_block "
                f"block_id={block_id} "
                f"error_index={error_index} "
                f"text_err={raw_match!r}"
            )
            continue

        # context_err также должен быть буквальным фрагментом document_block.
        #
        # Если контекст некорректен, post_proc не сможет надёжно
        # восстановить позицию замечания.
        if not raw_context or raw_context not in llm_block_text:
            log.warning(
                f"LLM run_format_check: context_err отсутствует в document_block "
                f"block_id={block_id} "
                f"error_index={error_index} "
                f"context_err={raw_context!r}"
            )
            # continue

        # --------------------------------------------------------------------
        # 5.1. Проверка offsets, возвращённых LLM
        # --------------------------------------------------------------------

        # Получаем start/end из Pydantic-модели.
        raw_start = getattr(err, "start", None)
        raw_end = getattr(err, "end", None)

        # По умолчанию offsets считаем ненадёжными.
        safe_start: Optional[int] = None
        safe_end: Optional[int] = None

        # Координаты сохраняем только при одновременном выполнении условий:
        # - исходный блок не был обрезан;
        # - start/end действительно указывают на text_err.
        if (
            not was_trimmed
            and isinstance(raw_start, int)
            and isinstance(raw_end, int)
            and validate_llm_offsets(
                llm_block_text,
                raw_start,
                raw_end,
                raw_match,
            )
        ):
            safe_start = raw_start
            safe_end = raw_end

        # Если offsets не прошли проверку, их восстановит post_proc()
        # по связке context + match.
        if safe_start is None or safe_end is None:
            log.debug(
                f"LLM run_format_check: offsets переданы в post_proc "
                f"block_id={block_id} "
                f"error_index={error_index} "
                f"was_trimmed={was_trimmed}"
            )

        # --------------------------------------------------------------------
        # 5.2. Нормализация полей для Word.Range.search()
        # --------------------------------------------------------------------

        # sanitize_text() в текущем проекте является async-функцией,
        # поэтому обязательно вызываем её через await.
        #
        # Она удаляет служебные символы Word, soft hyphen
        # и нормализует неразрывные пробелы.
        safe_match = await sanitize_text(raw_match)
        safe_context = await sanitize_text(raw_context)
        safe_correct = await sanitize_text(raw_correct)

        # После нормализации match не должен стать пустым.
        if not safe_match:
            log.warning(
                f"LLM run_format_check: match пуст после sanitize_text "
                f"block_id={block_id} "
                f"error_index={error_index}"
            )
            continue

        # Ограничиваем сообщение контрактом prompt.
        # Даже если модель вернула слишком длинное объяснение,
        # frontend получает компактное сообщение.
        safe_message = raw_message[:160].strip()

        if not safe_message:
            safe_message = "Нарушение требований к оформлению документа."

        # --------------------------------------------------------------------
        # 5.3. Нормализация критичности
        # --------------------------------------------------------------------

        # Разрешённые значения критичности по контракту LLM.
        allowed_critic_values = {"low", "medium", "high"}

        # Неизвестную критичность заменяем безопасным значением medium.
        if critic_err not in allowed_critic_values:
            critic_err = "medium"

        # Преобразуем critic_err в severity общего API.
        #
        # low    -> info
        # medium -> warning
        # high   -> error
        severity_by_critic = {
            "low": "info",
            "medium": "warning",
            "high": "error",
        }

        severity = severity_by_critic[critic_err]

        # --------------------------------------------------------------------
        # 5.4. Формирование стабильного идентификатора ошибки
        # --------------------------------------------------------------------

        # Источник стабильного ID включает содержательные признаки ошибки.
        #
        # Благодаря этому одинаковая ошибка в одном и том же блоке
        # получает одинаковый err_id при повторном анализе.
        stable_err_id_source = "|".join(
            [
                block_id,
                "LLM_FORMAT_ERR",
                safe_match,
                safe_context,
                safe_correct,
            ]
        )

        # SHA-1 используется не для криптографической защиты,
        # а как компактный детерминированный технический идентификатор.
        stable_err_id = hashlib.sha1(
            stable_err_id_source.encode("utf-8")
        ).hexdigest()

        # --------------------------------------------------------------------
        # 5.5. Сборка итогового issue
        # --------------------------------------------------------------------

        issue: Dict[str, Any] = {
            # ID Word-блока для привязки замечания.
            "blockId": block_id,

            # Уровень критичности в контракте frontend/backend.
            "severity": severity,

            # Фиксированный код Rule 1.
            #
            # Не строим его из ответа модели, чтобы модель
            # не могла изменить маршрутизацию замечания по вкладкам.
            "ruleCode": "LLM_FORMAT_ERR",

            # Короткое объяснение для панели Word Add-in.
            "message": safe_message,

            # Расширенные данные для post_proc и frontend-якорей.
            "meta": {
                # Тип исходного Word-блока.
                "blockType": block_type,

                # Стабильный ID конкретного замечания.
                "err_id": stable_err_id,

                # Проверенные offsets либо None.
                #
                # post_proc() сможет восстановить их через context + match.
                "start": safe_start,
                "end": safe_end,

                # Буквальный ошибочный фрагмент для Word.Range.search().
                "match": safe_match,

                # Локальный контекст для восстановления позиции ошибки.
                "context": safe_context,

                # Критичность в исходном контракте LLM.
                "critic_err": critic_err,

                # Предлагаемый вариант исправления.
                "correct_err": safe_correct,

                # Тип ошибки для диагностики и обратной совместимости.
                "type_err": "format_err",
            },
        }

        # Добавляем доказанное и нормализованное замечание
        # в результат текущего блока.
        issues.append(issue)

        log.debug(
            f"LLM run_format_check: issue accepted "
            f"block_id={block_id} "
            f"error_index={error_index} "
            f"match={safe_match!r} "
            f"severity={severity}"
        )

    log.debug(
        f"LLM run_format_check: done "
        f"block_id={block_id} "
        f"issues={len(issues)}"
    )

    return issues


async def run_tz_check(
    block: Dict[str, Any],
    tz_context: Dict[str, Any],
    doc_context: Optional[Dict[str, Any]] = None,
) -> List[Dict[str, Any]]:
    """
    Проверяет один блок документа только по Правилу 2 — соответствие ТЗ.


    Args:
        block: Словарь одного Word-блока.

        tz_context: Compact JSON технического задания.
            Пример структуры:
            {
                "groups": {
                    "group_1": {
                        "params": {
                            "Гарантийный срок эксплуатации": "5 лет"
                        }
                    }
                },
                "article_index": {
                    "MVA20-1-016-C": "group_1"
                }
            }
        doc_context:  общая информация о проверяемом документе.

    Returns:
        List[Dict[str, Any]]: Список замечаний в контракте backend RuleIssue.

    Применяется:
        В функции, которая запускает отдельные проверки Rule 1, Rule 2 и Rule 3
        для одного подготовленного блока.
    """

    # Результирующий список замечаний по текущему блоку.
    issues: List[Dict[str, Any]] = []

    # -------------------------------------------------------------------------
    # 1. НОРМАЛИЗАЦИЯ ВХОДНОГО БЛОКА
    # -------------------------------------------------------------------------

    # Приводим вход к обычному dict.
    # Это позволяет функции безопасно работать даже в случае, если позднее
    # вместо dict будет передана Pydantic-модель WordBlock.
    safe_block = _block_to_dict(block)

    # Получаем идентификатор блока, необходимый для API-контракта и err_id.
    block_id = str(safe_block.get("id", "") or "").strip()

    # Получаем тип Word-блока: paragraph, table, heading или list.
    block_type = str(safe_block.get("type", "") or "").strip()

    # Получаем исходный текст блока.
    # Именно этот текст является единственным объектом проверки.
    source_block_text = str(safe_block.get("text", "") or "")

    # Нормализуем контекст ТЗ.
    # При None или неверном типе используем пустой словарь.
    safe_tz_context: Dict[str, Any] = (
        tz_context
        if isinstance(tz_context, dict)
        else {}
    )

    # Логируем начало отдельной проверки Правила 2.
    log.debug(
        "LLM run_tz_check: start block_id=%s block_type=%s text_len=%s",
        block_id,
        block_type,
        len(source_block_text),
    )

    # -------------------------------------------------------------------------
    # 2. ПРОВЕРКА ОБЯЗАТЕЛЬНЫХ ВХОДНЫХ ДАННЫХ
    # -------------------------------------------------------------------------

    # Пустой текст проверять невозможно.
    if not source_block_text.strip():
        log.debug(
            "LLM run_tz_check: skip empty block block_id=%s",
            block_id,
        )
        return []

    # Без загруженного ТЗ Правило 2 не имеет нормативной базы.
    # Важно: отсутствие tz_context не является ошибкой документа.
    if not safe_tz_context:
        log.debug(
            "LLM run_tz_check: skip because tz_context is empty block_id=%s",
            block_id,
        )
        return []

    # -------------------------------------------------------------------------
    # 3. ПОДГОТОВКА ТЕКСТА И ТЗ ДЛЯ LLM
    # -------------------------------------------------------------------------

    # Ограничиваем размер текста блока согласно общей защите от переполнения
    # prompt и structured output.
    llm_block_text = trim_block_for_llm(source_block_text)

    # Запоминаем факт обрезки.
    # Если текст был обрезан, координаты LLM нельзя считать координатами
    # полного исходного блока без дополнительной проверки.
    was_trimmed = len(llm_block_text) != len(source_block_text)

    # Сериализуем compact JSON ТЗ в компактную JSON-строку.
    # ensure_ascii=False внутри dump_tz_context сохраняет русский текст.
    tz_json = dump_tz_context(safe_tz_context)

    doc_json = dump_doc_context(
        doc_context
    )  # Готовим общий контекст паспорта для выбора продукции.

    # -------------------------------------------------------------------------
    # 4. СОЗДАНИЕ И КЭШИРОВАНИЕ ОТДЕЛЬНОЙ ЦЕПОЧКИ RULE 2
    # -------------------------------------------------------------------------

    # Собираем runnable chain:
    # входные данные → prompt → structured LLM.
    _tz_llm_chain = get_tz_chain()

    # -------------------------------------------------------------------------
    # 5. АСИНХРОННЫЙ ВЫЗОВ LLM
    # -------------------------------------------------------------------------

    try:
        # Передаём только данные, разрешённые для Rule 2.
        async with LLM_REQUEST_SEM:

            try:
                # Выполняем исходную проверку по ТЗ.
                llm_out: LlmOutStructure = await _tz_llm_chain.ainvoke(
                    {
                        # Нормативный контекст ТЗ.
                        "tz_json": tz_json,

                        # Общая информация о продукции.
                        "doc_context": doc_json,

                        # Исходный текст проверяемого блока.
                        "document_block": llm_block_text,
                    }
                )

            except ValidationError as validation_err:

                # Пробуем восстановить JSON уже полученного ответа.
                # Новый запрос к LLM не выполняется.
                llm_out = recover_llm_json(validation_err)

                # Сообщаем об успешном восстановлении.
                log.debug(
                    "LLM run_tz_check: recovered JSON block_id=%s",
                    block_id,
                )

    except Exception as err:
        # Ошибка одного LLM-вызова не должна останавливать анализ документа.
        log.exception(
            "LLM run_tz_check: LLM exception block_id=%s error=%s",
            block_id,
            err,
        )

        # Возвращаем пустой список замечаний вместо падения всего pipeline.
        return []

    # Защита от неожиданного пустого ответа chain.
    if llm_out is None:
        log.warning(
            "LLM run_tz_check: LLM returned None block_id=%s",
            block_id,
        )
        return []

    # Получаем список ответов модели.
    llm_errors = list(getattr(llm_out, "llm_out", []) or [])

    log.debug(
        "LLM run_tz_check: LLM completed block_id=%s raw_errors=%s",
        block_id,
        len(llm_errors),
    )

    # -------------------------------------------------------------------------
    # 6. ПРЕОБРАЗОВАНИЕ ОТВЕТА LLM В BACKEND ISSUE CONTRACT
    # -------------------------------------------------------------------------

    # Набор используется для удаления дублей внутри одного ответа модели.
    seen_issue_ids: set[str] = set()

    # Обрабатываем каждое замечание модели отдельно.
    for err in llm_errors:

        # ---------------------------------------------------------------------
        # 6.1. ЖЁСТКАЯ ФИЛЬТРАЦИЯ ПО ТИПУ ПРАВИЛА
        # ---------------------------------------------------------------------

        # Нормализуем тип замечания.
        err_type = str(getattr(err, "type_err", "") or "").strip().lower()

        # Эта функция должна возвращать исключительно tz_err.
        # Даже если модель нарушила prompt и вернула format_err/tt_err,
        # такое замечание не попадёт в итоговый результат.
        if err_type != "tz_err":
            log.warning(
                "LLM run_tz_check: foreign issue type skipped "
                "block_id=%s type_err=%s",
                block_id,
                err_type,
            )
            continue

        # ---------------------------------------------------------------------
        # 6.2. ИЗВЛЕЧЕНИЕ ПОЛЕЙ ОТВЕТА
        # ---------------------------------------------------------------------

        # Получаем непосредственный ошибочный фрагмент.
        raw_match = str(getattr(err, "text_err", "") or "")

        # Получаем буквальный контекст ошибки.
        raw_context = str(getattr(err, "context_err", "") or "")

        # Получаем предлагаемое нормативное значение.
        raw_correct = str(getattr(err, "correct_err", "") or "")

        # Получаем пояснение для панели Word.
        message = str(getattr(err, "msg_err", "") or "").strip()

        # Получаем критичность замечания.
        critic_err = (
            str(getattr(err, "critic_err", "") or "")
            .strip()
            .lower()
        )

        # Получаем координаты, возвращённые моделью.
        raw_start = getattr(err, "start", None)
        raw_end = getattr(err, "end", None)

        # ---------------------------------------------------------------------
        # 6.3. АСИНХРОННАЯ ОЧИСТКА ТЕКСТОВЫХ ПОЛЕЙ
        # ---------------------------------------------------------------------

        # sanitize_text находится в app.utils и является async-функцией.
        # Поэтому каждый её вызов обязательно выполняется через await.
        safe_match = await sanitize_text(raw_match)

        # Для таблиц запрещаем ошибочным фрагментам
        # пересекать границы ячеек или строк.
        if block_type.strip().lower() == "table":

            # Табуляции и переносы строк указывают на возможное
            # пересечение границ ячеек или строк.
            if any(char in safe_match for char in ("\t", "\n", "\r")):
                # Фиксируем причину отклонения замечания.
                log.debug(
                    "LLM: пропущено замечание с некорректным "
                    "text_err внутри таблицы block_id=%s",
                    block_id,
                )

                # Не допускаем восстановления такого замечания через context.
                continue

        # Очищаем контекст от служебных символов Word.
        safe_context = await sanitize_text(raw_context)
        # Ограничиваем context одной строкой таблицы.
        safe_context = normalize_table_context(
            block_text=source_block_text,  # Полный исходный Word-блок.
            context=safe_context,  # Контекст, который вернула LLM.
            match=safe_match,  # Ошибочный фрагмент.
            block_type=block_type,  # Тип блока Word. Для paragraph функция ничего не меняет.
        )

        # Очищаем предлагаемый вариант исправления.
        safe_correct = await sanitize_text(raw_correct)

        # Пустой match невозможно использовать для поиска и создания якоря.
        if not safe_match.strip():
            log.warning(
                "LLM run_tz_check: empty match skipped block_id=%s",
                block_id,
            )
            continue

        # Пустое сообщение заменяем нейтральным текстом.
        if not message:
            message = "Значение характеристики не соответствует данным ТЗ."

        # Ограничиваем длину message контрактом prompt.
        message = message[:160]

        # ---------------------------------------------------------------------
        # 6.4. ПРОВЕРКА НАЛИЧИЯ ФРАГМЕНТОВ В ИСХОДНОМ БЛОКЕ
        # ---------------------------------------------------------------------

        # Нормализованная версия полного исходного блока нужна только
        # для безопасной проверки вхождения очищенного текста.
        safe_source_block_text = await sanitize_text(source_block_text)

        # text_err обязан существовать в исходном блоке.
        if safe_match not in safe_source_block_text:
            log.warning(
                "LLM run_tz_check: match not found in source block "
                "block_id=%s match=%r",
                block_id,
                safe_match,
            )
            continue

        # context_err также должен быть буквальным фрагментом исходного блока.
        # Если LLM вернула неверный context_err, сохраняем match как минимальный
        # надёжный контекст, чтобы замечание не потерялось полностью.
        if not safe_context or safe_context not in safe_source_block_text:
            log.debug(
                "LLM run_tz_check: invalid context replaced by match "
                "block_id=%s context=%r",
                block_id,
                safe_context,
            )
            safe_context = safe_match

        # ---------------------------------------------------------------------
        # 6.5. ПРОВЕРКА И ВОССТАНОВЛЕНИЕ КООРДИНАТ
        # ---------------------------------------------------------------------

        # По умолчанию координаты считаются неразрешёнными.
        safe_start: Optional[int] = None
        safe_end: Optional[int] = None

        # Проверяем, что модель действительно вернула целые числа.
        offsets_are_int = (
            isinstance(raw_start, int)
            and not isinstance(raw_start, bool)
            and isinstance(raw_end, int)
            and not isinstance(raw_end, bool)
        )

        # Координаты принимаются только:
        # - если блок не был обрезан;
        # - если start/end имеют тип int;
        # - если validate_llm_offsets подтверждает точное совпадение.
        if (
            not was_trimmed
            and offsets_are_int
            and validate_llm_offsets(
                source_block_text,
                raw_start,
                raw_end,
                raw_match,
            )
        ):
            safe_start = raw_start
            safe_end = raw_end

        else:
            # Если координаты модели неверны, пытаемся восстановить их
            # детерминированным поиском match в исходном тексте.
            first_position = safe_source_block_text.find(raw_match)

            # Проверяем, что найдено ровно одно вхождение.
            # При нескольких вхождениях координаты неоднозначны,
            # поэтому оставляем start/end равными None.
            if first_position >= 0:
                second_position = safe_source_block_text.find(
                    raw_match,
                    first_position + 1,
                )

                # Если совпадение единственное, сохраняем точные индексы.
                if second_position == -1:
                    safe_start = first_position
                    safe_end = first_position + len(raw_match)

        # ---------------------------------------------------------------------
        # 6.6. НОРМАЛИЗАЦИЯ КРИТИЧНОСТИ
        # ---------------------------------------------------------------------

        # Приводим значение модели к поддерживаемому набору.
        if critic_err not in {"low", "medium", "high"}:
            critic_err = "medium"

        # Преобразуем внутреннюю критичность LLM в severity API.
        severity_by_critic = {
            "low": "info",
            "medium": "warning",
            "high": "error",
        }

        severity = severity_by_critic[critic_err]

        # ---------------------------------------------------------------------
        # 6.7. ФОРМИРОВАНИЕ СТАБИЛЬНОГО ИДЕНТИФИКАТОРА
        # ---------------------------------------------------------------------

        # В состав err_id включаем только устойчивые данные замечания.
        # Поэтому одинаковое замечание при повторном анализе получает тот же ID.
        stable_err_id_source = "|".join(
            [
                block_id,
                "LLM_TZ_ERR",
                safe_match,
                safe_context,
                safe_correct,
            ]
        )

        # SHA-1 используется не для криптографической защиты,
        # а как компактный детерминированный идентификатор.
        stable_err_id = hashlib.sha1(
            stable_err_id_source.encode("utf-8")
        ).hexdigest()

        # Удаляем полные дубли внутри ответа одного LLM-вызова.
        if stable_err_id in seen_issue_ids:
            log.debug(
                "LLM run_tz_check: duplicate skipped "
                "block_id=%s err_id=%s",
                block_id,
                stable_err_id,
            )
            continue

        # Запоминаем ID принятого замечания.
        seen_issue_ids.add(stable_err_id)

        # ---------------------------------------------------------------------
        # 6.8. ФОРМИРОВАНИЕ ИТОГОВОГО ISSUE
        # ---------------------------------------------------------------------

        issue_dict: Dict[str, Any] = {
            # Идентификатор Word-блока.
            "blockId": block_id,

            # Нормализованная критичность для API.
            "severity": severity,

            # Фиксированный код отдельной проверки Правила 2.
            "ruleCode": "LLM_TZ_ERR",

            # Текст пояснения для панели замечаний.
            "message": message,

            # Технические данные замечания.
            "meta": {
                # Тип исходного Word-блока.
                "blockType": block_type,

                # Устойчивый идентификатор замечания.
                "err_id": stable_err_id,

                # Координаты могут быть None при неоднозначной привязке.
                "start": safe_start,
                "end": safe_end,

                # Ошибочный фрагмент для поиска Word Range.search().
                "match": safe_match,

                # Буквальный контекст для дополнительной привязки.
                "context": safe_context,

                # Исходная критичность structured output.
                "critic_err": critic_err,

                # Нормативное значение или исправленный фрагмент.
                "correct_err": safe_correct,

                # Тип ошибки в контракте LLM.
                "type_err": "tz_err",
            },
        }

        # Добавляем валидированное замечание в результат.
        issues.append(issue_dict)

        log.debug(
            "LLM run_tz_check: issue accepted "
            "block_id=%s match=%r correct=%r severity=%s",
            block_id,
            safe_match,
            safe_correct,
            severity,
        )

    # -------------------------------------------------------------------------
    # 7. ЗАВЕРШЕНИЕ ПРОВЕРКИ
    # -------------------------------------------------------------------------
    log.debug(
        "LLM run_tz_check: done block_id=%s issues=%s",
        block_id,
        len(issues),
    )

    return issues


async def run_tt_check(
    block: Dict[str, Any],
    tt_context: Dict[str, Any],
    doc_context: Optional[Dict[str, Any]] = None,
) -> List[Dict[str, Any]]:
    """
    Проверяет один блок документа только по Правилу 3 —
    соответствие техническим требованиям ТТ.

    Args:
        block:
            Словарь одного Word-блока.

        tt_context:
            Подготовленный контекст ТТ в формате:
            {
                "chunks": [
                    {
                        "text": "Текст требования ТТ или структурированный JSON Excel ТТ",
                        "applies_to_entities": [
                            "проверяемая сущность"
                        ]
                    }
                ]
            }
        doc_context:  общая информация о проверяемом документе.

    Returns:
        List[Dict[str, Any]]:
            Список замечаний в backend-контракте RuleIssue.

    Применяется:
        В функции, которая запускает отдельные проверки Rule 1, Rule 2
        и Rule 3 для одного подготовленного блока.
    """

    # Результирующий список замечаний по текущему блоку.
    issues: List[Dict[str, Any]] = []

    # -------------------------------------------------------------------------
    # 1. НОРМАЛИЗАЦИЯ ВХОДНЫХ ДАННЫХ
    # -------------------------------------------------------------------------

    # Приводим входной Word-блок к обычному словарю.
    # Это обеспечивает совместимость как с dict, так и с Pydantic-моделью.
    safe_block = _block_to_dict(block)

    # Получаем идентификатор Word-блока для backend-контракта и err_id.
    block_id = str(
        safe_block.get("id", "") or ""
    ).strip()

    # Получаем тип блока: paragraph, table, heading или list.
    block_type = str(
        safe_block.get("type", "") or ""
    ).strip()

    # Получаем исходный текст блока.
    # Только этот текст является объектом проверки.
    source_block_text = str(
        safe_block.get("text", "") or ""
    )

    # Принимаем только словарь.
    # Повторную обработку chunks и applies_to_entities здесь не выполняем.
    safe_tt_context: Dict[str, Any] = (
        tt_context
        if isinstance(tt_context, dict)
        else {}
    )

    # Получаем уже подготовленный список нормативных чанков.
    tt_chunks = safe_tt_context.get("chunks", [])

    # -------------------------------------------------------------------------
    # 2. ПРОВЕРКА ОБЯЗАТЕЛЬНЫХ ВХОДНЫХ ДАННЫХ
    # -------------------------------------------------------------------------

    # Пустой текст блока проверять невозможно.
    if not source_block_text.strip():
        log.debug(
            "LLM run_tt_check: skip empty block block_id=%s",
            block_id,
        )
        return []

    # Для Rule 3 нормативной базой является непустой список chunks.
    # Отсутствие релевантных чанков не является ошибкой документа.
    if not isinstance(tt_chunks, list) or not tt_chunks:
        log.debug(
            "LLM run_tt_check: skip because TT chunks are empty "
            "block_id=%s",
            block_id,
        )
        return []

    # -------------------------------------------------------------------------
    # 3. ПОДГОТОВКА ТЕКСТА И КОНТЕКСТА ТТ ДЛЯ LLM
    # -------------------------------------------------------------------------

    # Ограничиваем длину блока общей защитой от переполнения prompt.
    llm_block_text = trim_block_for_llm(source_block_text)

    # Запоминаем факт обрезки текста.
    # Координаты LLM нельзя напрямую применять к полному тексту,
    # если в модель была отправлена только его часть.
    was_trimmed = (
        len(llm_block_text) != len(source_block_text)
    )

    # Сериализуем уже подготовленный tt_context в компактный JSON.
    # Никакая дополнительная обработка чанков здесь не выполняется.
    tt_json = dump_tt_context(safe_tt_context)


    doc_json = dump_doc_context(
        doc_context
    )  # Сериализуем общие сведения о продукции документа.

    # -------------------------------------------------------------------------
    # 4. СОЗДАНИЕ И КЭШИРОВАНИЕ ОТДЕЛЬНОЙ ЦЕПОЧКИ RULE 3
    # -------------------------------------------------------------------------
    # Собираем runnable chain:
    # входные данные → prompt → structured LLM.
    _tt_llm_chain = get_tt_chain()

    # -------------------------------------------------------------------------
    # 5. АСИНХРОННЫЙ ВЫЗОВ LLM
    # -------------------------------------------------------------------------

    try:
        # Передаём в Rule 3 только контекст ТТ и проверяемый блок.
        async with LLM_REQUEST_SEM:
            try:
                llm_out: LlmOutStructure = await _tt_llm_chain.ainvoke(
                    {
                        "doc_context": doc_json,  # Общие сведения о продукции паспорта.
                        "tt_json": tt_json, # Нормативный ТТ-контекст.
                        "document_block": llm_block_text, # Текущий проверяемый блок.
                    }
                )
            except ValidationError as validation_err:

                # Пробуем восстановить JSON уже полученного ответа.
                # Новый запрос к LLM не выполняется.
                llm_out = recover_llm_json(validation_err)

                # Сообщаем об успешном восстановлении.
                log.debug(
                    "LLM run_tt_check: recovered JSON block_id=%s",
                    block_id,
                )

    except Exception as err:
        # Ошибка одной проверки не должна прерывать анализ всего документа.
        log.exception(
            "LLM run_tt_check: LLM exception "
            "block_id=%s error=%s",
            block_id,
            err,
        )

        return []

    # Защищаемся от неожиданного пустого ответа chain.
    if llm_out is None:
        log.warning(
            "LLM run_tt_check: LLM returned None "
            "block_id=%s",
            block_id,
        )
        return []

    # Получаем список замечаний из structured output.
    llm_errors = list(
        getattr(llm_out, "llm_out", []) or []
    )

    log.debug(
        "LLM run_tt_check: LLM completed "
        "block_id=%s raw_errors=%s",
        block_id,
        len(llm_errors),
    )

    # -------------------------------------------------------------------------
    # 6. ПРЕОБРАЗОВАНИЕ ОТВЕТА LLM В BACKEND ISSUE CONTRACT
    # -------------------------------------------------------------------------

    # Используется для удаления дублей внутри одного ответа LLM.
    seen_issue_ids: set[str] = set()

    # Нормализуем полный исходный блок один раз.
    # Результат используется для проверки match и context.
    safe_source_block_text = await sanitize_text(
        source_block_text
    )

    # Обрабатываем каждое замечание модели отдельно.
    for err in llm_errors:

        # ---------------------------------------------------------------------
        # 6.1. ЖЁСТКАЯ ФИЛЬТРАЦИЯ ПО ТИПУ ПРАВИЛА
        # ---------------------------------------------------------------------

        # Нормализуем тип замечания.
        err_type = str(
            getattr(err, "type_err", "") or ""
        ).strip().lower()

        # Эта функция возвращает исключительно tt_err.
        # Ошибки других типов отбрасываются.
        if err_type != "tt_err":
            log.debug(
                "LLM run_tt_check: foreign issue type skipped "
                "block_id=%s type_err=%s",
                block_id,
                err_type,
            )
            continue

        # ---------------------------------------------------------------------
        # 6.2. ИЗВЛЕЧЕНИЕ ПОЛЕЙ ОТВЕТА
        # ---------------------------------------------------------------------

        # Получаем непосредственный ошибочный фрагмент документа.
        raw_match = str(
            getattr(err, "text_err", "") or ""
        )

        # Получаем буквальный контекст найденного нарушения.
        raw_context = str(
            getattr(err, "context_err", "") or ""
        )

        # Получаем предлагаемое исправление.
        raw_correct = str(
            getattr(err, "correct_err", "") or ""
        )

        # Получаем пояснение для панели замечаний.
        message = str(
            getattr(err, "msg_err", "") or ""
        ).strip()

        # Получаем критичность замечания.
        critic_err = str(
            getattr(err, "critic_err", "") or ""
        ).strip().lower()

        # Получаем координаты, возвращённые моделью.
        raw_start = getattr(err, "start", None)
        raw_end = getattr(err, "end", None)

        # ---------------------------------------------------------------------
        # 6.3. АСИНХРОННАЯ ОЧИСТКА ТЕКСТОВЫХ ПОЛЕЙ
        # ---------------------------------------------------------------------

        # sanitize_text находится в app.utils и является async-функцией.
        safe_match = await sanitize_text(raw_match)

        # Для таблиц запрещаем ошибочным фрагментам
        # пересекать границы ячеек или строк.
        if block_type.strip().lower() == "table":

            # Табуляции и переносы строк указывают на возможное
            # пересечение границ ячеек или строк.
            if any(char in safe_match for char in ("\t", "\n", "\r")):
                # Фиксируем причину отклонения замечания.
                log.debug(
                    "LLM: пропущено замечание с некорректным "
                    "text_err внутри таблицы block_id=%s",
                    block_id,
                )

                # Не допускаем восстановления такого замечания через context.
                continue

        # Очищаем контекст от служебных символов Word.
        safe_context = await sanitize_text(raw_context)
        # Ограничиваем context одной строкой таблицы.
        safe_context = normalize_table_context(
            block_text=source_block_text,  # Полный исходный Word-блок.
            context=safe_context,  # Контекст, который вернула LLM.
            match=safe_match,  # Ошибочный фрагмент.
            block_type=block_type,  # Тип блока Word. Для paragraph функция ничего не меняет.
        )

        # Очищаем предлагаемое исправление.
        safe_correct = await sanitize_text(raw_correct)

        # Пустой match нельзя использовать для поиска фрагмента в Word.
        if not safe_match.strip():
            log.warning(
                "LLM run_tt_check: empty match skipped "
                "block_id=%s",
                block_id,
            )
            continue

        # Подставляем нейтральное сообщение,
        # если LLM не вернула пояснение.
        if not message:
            message = (
                "Текст документа не соответствует "
                "требованию технического задания ТТ."
            )

        # Ограничиваем длину сообщения контрактом prompt.
        message = message[:160]

        # ---------------------------------------------------------------------
        # 6.4. ПРОВЕРКА ФРАГМЕНТОВ ПО ИСХОДНОМУ БЛОКУ
        # ---------------------------------------------------------------------

        # text_err обязан буквально присутствовать в проверяемом блоке.
        if safe_match not in safe_source_block_text:
            log.debug(
                "LLM run_tt_check: match not found in source block "
                "block_id=%s match=%r",
                block_id,
                safe_match,
            )
            continue

        # context_err должен быть буквальным фрагментом исходного текста.
        # Если контекст некорректен, используем match как минимальный
        # надёжный контекст для последующей привязки замечания.
        if (
            not safe_context
            or safe_context not in safe_source_block_text
        ):
            log.debug(
                "LLM run_tt_check: invalid context replaced by match "
                "block_id=%s context=%r",
                block_id,
                safe_context,
            )

            safe_context = safe_match

        # ---------------------------------------------------------------------
        # 6.5. ПРОВЕРКА И ВОССТАНОВЛЕНИЕ КООРДИНАТ
        # ---------------------------------------------------------------------

        # По умолчанию координаты считаются неразрешёнными.
        safe_start: Optional[int] = None
        safe_end: Optional[int] = None

        # bool является подклассом int, поэтому исключаем его отдельно.
        offsets_are_int = (
            isinstance(raw_start, int)
            and not isinstance(raw_start, bool)
            and isinstance(raw_end, int)
            and not isinstance(raw_end, bool)
        )

        # Принимаем координаты модели только при точном совпадении.
        if (
            not was_trimmed
            and offsets_are_int
            and validate_llm_offsets(
                source_block_text,
                raw_start,
                raw_end,
                raw_match,
            )
        ):
            safe_start = raw_start
            safe_end = raw_end

        else:
            # При неверных координатах пытаемся найти match
            # детерминированным поиском в исходном тексте.
            first_position = safe_source_block_text.find(
                raw_match
            )

            if first_position >= 0:
                # Проверяем наличие второго совпадения.
                second_position = safe_source_block_text.find(
                    raw_match,
                    first_position + 1,
                )

                # Координаты сохраняются только при одном совпадении.
                if second_position == -1:
                    safe_start = first_position
                    safe_end = (
                        first_position + len(raw_match)
                    )

        # ---------------------------------------------------------------------
        # 6.6. НОРМАЛИЗАЦИЯ КРИТИЧНОСТИ
        # ---------------------------------------------------------------------

        # При неизвестной критичности используем среднее значение.
        if critic_err not in {"low", "medium", "high"}:
            critic_err = "medium"

        # Преобразуем critic_err модели в severity backend API.
        severity_by_critic = {
            "low": "info",
            "medium": "warning",
            "high": "error",
        }

        severity = severity_by_critic[critic_err]

        # ---------------------------------------------------------------------
        # 6.7. ФОРМИРОВАНИЕ СТАБИЛЬНОГО ИДЕНТИФИКАТОРА
        # ---------------------------------------------------------------------

        # Формируем устойчивую строку-основание для идентификатора.
        stable_err_id_source = "|".join(
            [
                block_id,
                "LLM_TT_ERR",
                safe_match,
                safe_context,
                safe_correct,
            ]
        )

        # SHA-1 используется как компактный детерминированный ID,
        # а не как средство криптографической защиты.
        stable_err_id = hashlib.sha1(
            stable_err_id_source.encode("utf-8")
        ).hexdigest()

        # Удаляем полные дубли замечаний одного LLM-вызова.
        if stable_err_id in seen_issue_ids:
            log.debug(
                "LLM run_tt_check: duplicate skipped "
                "block_id=%s err_id=%s",
                block_id,
                stable_err_id,
            )
            continue

        # Запоминаем идентификатор принятого замечания.
        seen_issue_ids.add(stable_err_id)

        # ---------------------------------------------------------------------
        # 6.8. ФОРМИРОВАНИЕ ИТОГОВОГО ISSUE
        # ---------------------------------------------------------------------
        issue: Dict[str, Any] = {
            # Идентификатор проверенного Word-блока.
            "blockId": block_id,

            # Нормализованная критичность для backend API.
            "severity": severity,

            # Фиксированный код отдельной проверки Правила 3.
            "ruleCode": "LLM_TT_ERR",

            # Пояснение, отображаемое в панели Word.
            "message": message,

            # Технические данные замечания.
            "meta": {
                # Тип исходного Word-блока.
                "blockType": block_type,

                # Устойчивый идентификатор замечания.
                "err_id": stable_err_id,

                # Координаты могут быть None при неоднозначной привязке.
                "start": safe_start,
                "end": safe_end,

                # Ошибочный фрагмент для Word Range.search().
                "match": safe_match,

                # Буквальный контекст для дополнительной привязки.
                "context": safe_context,

                # Исходная критичность structured output.
                "critic_err": critic_err,

                # Предлагаемый вариант исправления.
                "correct_err": safe_correct,

                # Тип ошибки в контракте LLM.
                "type_err": "tt_err",
            },
        }

        # Добавляем валидированное замечание в итоговый список.
        issues.append(issue)

        log.debug(
            "LLM run_tt_check: issue accepted "
            "block_id=%s match=%r correct=%r severity=%s",
            block_id,
            safe_match,
            safe_correct,
            severity,
        )

    # -------------------------------------------------------------------------
    # 7. ЗАВЕРШЕНИЕ ПРОВЕРКИ
    # -------------------------------------------------------------------------
    log.debug(
        "LLM run_tt_check: done "
        "block_id=%s issues=%s",
        block_id,
        len(issues),
    )

    return issues
